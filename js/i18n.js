let msPromise = null;
/**
 * Load a language's strings (only Bahasa Melayu needs loading). Resolves
 * when t(lang, …) gives that language.
 */
export function loadLang(lang) {
  if (lang !== 'ms' || STRINGS.ms) return Promise.resolve();
  if (!msPromise) {
    msPromise = import('./i18n-ms.js').then((m) => { STRINGS.ms = m.default; }).catch(() => { msPromise = null; });
  }
  return msPromise;
}
// Start fetching Bahasa Melayu straight away for visitors who chose it.
try { if (JSON.parse(localStorage.getItem('palangic:lang')) === 'ms') loadLang('ms'); } catch { /* storage blocked */ }

export function t(lang, key, vars) {
  let str = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, v);
  return str;
}

/**
 * Fill every [data-i18n] text and [data-i18n-attr] attribute. If Bahasa
 * Melayu is still loading, English shows for a moment and the page is filled
 * again when it arrives (then 'dokujaga:i18n' fires so scripts can redraw).
 */
export function applyI18n(root, lang) {
  if (lang === 'ms' && !STRINGS.ms) {
    loadLang('ms').then(() => {
      if (!STRINGS.ms || root.documentElement.dataset.i18nLang !== 'ms') return;
      applyI18n(root, 'ms');
      root.dispatchEvent(new CustomEvent('dokujaga:i18n'));
    });
  }
  root.documentElement.dataset.i18nLang = lang === 'en' ? 'en' : 'ms';
  root.documentElement.lang = lang === 'en' ? 'en' : 'ms';
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(lang, el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(',').forEach((pair) => {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr.trim(), t(lang, key.trim()));
    });
  });
}

/** DD/MM/YYYY in local time. */
export function todayDMY(date = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return `${p(date.getDate())}/${p(date.getMonth() + 1)}/${date.getFullYear()}`;
}
